"""DEXPI mapping coverage: how much of a graph survives the DEXPI-structured export.

  python scripts/dexpi_coverage.py --split dataset_pid_val --split synthetic_val \\
      [--pred-dir outputs/preds/<run>] [--out docs/DEXPI_COVERAGE.md]

For each drawing (ground truth, and predictions if --pred-dir is given) the graph is
exported with `export/dexpi.py` and validated (XSD + DEXPI vocabulary). Reports per
subset: symbol instances mapped vs unmapped (by class), piping chains exported fully /
with one open end / dropped, instrument connections, and validation failures.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from pathlib import Path

from pid.config import load_config, resolve
from pid.export.dexpi import load_mapping, to_dexpi, validate_dexpi
from pid.export.graphml import read_graphml
from pid.io.drawing import Drawing
from pid.io.pid2graph import load_drawing, ref_from_uid

STRUCT = ("crossing", "ankle")


def collect(drawings: list[Drawing]) -> dict[str, Counter[str]]:
    agg: dict[str, Counter[str]] = defaultdict(Counter)
    for d in drawings:
        xml, rep = to_dexpi(d)
        agg["validation"]["drawings"] += 1
        agg["validation"]["invalid"] += bool(validate_dexpi(xml))
        for s in d.symbols:
            if s.cls not in STRUCT:
                agg["symbols"][s.cls] += 1
        agg["unmapped"].update(rep.unmapped_symbols)
        agg["chains"].update(rep.chains)
    return agg


def table(title: str, agg: dict[str, Counter[str]], mapping: dict[str, object]) -> list[str]:
    sym, unm, ch = agg["symbols"], agg["unmapped"], agg["chains"]
    total = sum(sym.values())
    mapped = total - sum(unm.values())
    lines = [f"### {title}", "",
             f"Drawings: {agg['validation']['drawings']}, failing DEXPI validation: "
             f"**{agg['validation']['invalid']}**.", "",
             "| class | instances | DEXPI class |", "|---|---|---|"]
    symbols = mapping["symbols"]
    assert isinstance(symbols, dict)
    for cls, n in sym.most_common():
        target = symbols[cls]["type"] if cls in symbols else "**unmapped**"
        lines.append(f"| {cls} | {n} | {target} |")
    lines.append(f"| **mapped share** | {mapped}/{total} = {mapped / max(total, 1):.1%} | |")
    piping = ch["piping"] + ch["piping_nonsolid"]
    full = piping - ch["piping_one_end_unmapped"]
    lines += ["", "| connections (terminal-to-terminal chains) | count |", "|---|---|",
              f"| piping, both ends mapped | {full} |",
              f"| piping, one end unmapped (open end) | {ch['piping_one_end_unmapped']} |",
              f"| piping chains drawn non-solid (line type not representable on a Pipe) "
              f"| {ch['piping_nonsolid']} |",
              f"| instrument ↔ piping (generator + measuring line) | {ch['instrument_piping']} |",
              f"| instrument ↔ instrument (signal conveying function) "
              f"| {ch['instrument_instrument']} |",
              f"| dropped: both ends unmapped | {ch['both_ends_unmapped_dropped']} |",
              f"| dropped: instrument to open end | {ch['instrument_open_dropped']} |", ""]
    return lines


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", action="append", required=True)
    ap.add_argument("--pred-dir")
    ap.add_argument("--out", default="docs/DEXPI_COVERAGE.md")
    args = ap.parse_args()
    cfg, mapping = load_config("data"), load_mapping()
    out = ["# DEXPI mapping coverage", "",
           f"Generated by `scripts/dexpi_coverage.py` (DEXPI {mapping['dexpi_version']}, "
           "mapping `src/pid/export/dexpi_mapping.yaml`). Ground truth shows what the "
           "export can represent at best; predictions show what the pipeline delivers.", ""]
    for split in args.split:
        uids = (resolve(cfg["splits"]["dir"]) / f"{split}.txt").read_text().split()
        gts = [load_drawing(ref_from_uid(u, cfg), cfg, with_size=False) for u in uids]
        out += [f"## {split}", ""] + table("Ground truth", collect(gts), mapping)
        if args.pred_dir and all((Path(args.pred_dir) / f"{u}.graphml").exists() for u in uids):
            preds = [read_graphml(Path(args.pred_dir) / f"{u}.graphml", cfg["label_map"])
                     for u in uids]
            out += table(f"Predictions ({Path(args.pred_dir).name})", collect(preds), mapping)
        print(f"done {split}")
    dest = resolve(args.out)
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
