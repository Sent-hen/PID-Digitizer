"""Regenerate every Milestone 5 table and figure from the saved metrics files.

  python scripts/make_report.py

Reads outputs/preds/<run>/metrics_<split>.json for the runs in configs/final_eval.yaml
and writes:
  * docs/FINAL_RESULTS.md      - all final tables
  * docs/robustness.png        - metric drop per stage under degradation
  * RESULTS.md and README.md   - the block between `<!-- final:start -->` and
                                 `<!-- final:end -->` (identical in both files)
Fails loudly if a run is missing or was produced by different weights.
"""

from __future__ import annotations

import json
import re
from typing import Any

from pid.config import load_config, resolve

START, END = "<!-- final:start -->", "<!-- final:end -->"
NAMES = {"dataset_pid_test": "Dataset-PID", "synthetic_test": "Synthetic",
         "open100_test": "OPEN100 (real)"}
CLASSES = ["general", "tank", "valve", "instrumentation", "pump", "arrow", "inlet_outlet"]


def load(run: str, split: str, sha: str | None) -> dict[str, Any]:
    f = resolve("outputs/preds") / run / f"metrics_{split}.json"
    if not f.exists():
        raise SystemExit(f"missing {f} - run scripts/final_eval.py first")
    m: dict[str, Any] = json.loads(f.read_text())
    if sha and not m.get("oracle_symbols") and m.get("weights_sha1") != sha:
        raise SystemExit(f"{f}: weights {m.get('weights_sha1')} != expected {sha}")
    return m


def f3(x: float) -> str:
    return "–" if x != x else f"{x:.3f}"


def headline(cfg: dict[str, Any], get: Any) -> list[str]:
    rows = ["| test set | n | Symbols mAP@0.5 | mAP@0.5:0.95 | Nodes AP@0.5 | Edge P / R / F1 "
            "| per-drawing F1 median / p10 | line-type acc | Edge mAP (solid / non-solid) |",
            "|---|---|---|---|---|---|---|---|---|"]
    for s in cfg["test_splits"]:
        m = get("final_test", s)
        e, em, pd = m["edges"], m["pid2graph_edge_map"], m["edges_per_drawing_f1"]
        rows.append(
            f"| {NAMES[s]} | {m['n_drawings']} | {f3(m['symbols']['mAP50'])} | "
            f"{f3(m['symbols']['mAP50_95'])} | {f3(m['node_AP50'])} | {f3(e['precision'])} / "
            f"{f3(e['recall'])} / **{f3(e['f1'])}** | {f3(pd['median'])} / {f3(pd['p10'])} | "
            f"{f3(e['line_type_accuracy'])} | **{f3(em['edge_mAP'])}** ({f3(em['AP_solid'])} / "
            f"{f3(em.get('AP_non-solid', float('nan')))}) |")
    return rows


def readme_block(cfg: dict[str, Any], get: Any, meta: dict[str, Any]) -> list[str]:
    rows = [START,
            f"Final test results (run once; detector `{cfg['weights']}` sha1 "
            f"`{cfg['weights_sha1']}`, commit `{meta['commit']}`, config hash "
            f"`{meta['config_hash']}`). Splits are ours: PID2Graph releases no training data "
            "(DATASET_NOTES.md). Generated by `scripts/make_report.py`.", "",
            "| test set | Symbols mAP@0.5 | Nodes AP@0.5 | Edge F1 | Edge mAP (PID2Graph protocol) "
            "| Edge F1 at degradation L1 / L2 / L3 |", "|---|---|---|---|---|---|"]
    for s in cfg["test_splits"]:
        m = get("final_test", s)
        deg = " / ".join(f3(get(f"final_test_L{lv}", s)["edges"]["f1"]) for lv in (1, 2, 3))
        rows.append(f"| {NAMES[s]} ({m['n_drawings']} sheets) | {f3(m['symbols']['mAP50'])} | "
                    f"{f3(m['node_AP50'])} | {f3(m['edges']['f1'])} | "
                    f"{f3(m['pid2graph_edge_map']['edge_mAP'])} | {deg} |")
    rows.append(END)
    return rows


def main() -> None:
    cfg = load_config("final_eval")
    sha = cfg["weights_sha1"]

    def get(run: str, split: str) -> dict[str, Any]:
        return load(run, split, sha)

    splits = cfg["test_splits"]
    # The pipeline commit is stored in each prediction's GraphML metadata.
    gpath = next((resolve("outputs/preds/final_test") / splits[0].split("_test")[0]).glob(
        "*.graphml"))
    mm = re.search(r'key="g_pipeline">([^<]+)<', gpath.read_text(encoding="utf-8"))
    meta = {"commit": mm.group(1) if mm else "?",
            "config_hash": get("final_test", splits[0]).get("config_hash", "?")}

    out = ["# Final results (Milestone 5)", "",
           "Generated by `scripts/make_report.py` from `outputs/preds/*/metrics_*.json`; do not "
           "edit by hand. Run matrix: `configs/final_eval.yaml`.", "",
           f"- Detector: `{cfg['weights']}` (sha1 `{sha}`); pipeline commit `{meta['commit']}`, "
           f"config hash `{meta['config_hash']}`.",
           "- Hardware: RTX 4070 Laptop 8 GB (thermally limited during these runs: timings "
           "are not comparable to earlier ones), Intel Core Ultra 9 185H, torch 2.14.1+cu132.",
           "- Every test configuration was run exactly once; nothing was tuned on test.", "",
           "## Headline (clean test sets)", ""] + headline(cfg, get)

    # per-class AP
    out += ["", "## Per-class AP@0.5 (test)", "",
            "| class | " + " | ".join(NAMES[s] for s in splits) + " |",
            "|---|" + "---|" * len(splits)]
    for c in CLASSES:
        cells = []
        for s in splits:
            v = get("final_test", s)["symbols"]["per_class_AP50"].get(c, float("nan"))
            cells.append(f3(v) if v == v else "– (absent)")
        out.append(f"| {c} | " + " | ".join(cells) + " |")

    # error propagation
    out += ["", "## Error propagation (oracle symbols vs detector)", "",
            "| test set | Nodes AP oracle / predicted | Edge F1 oracle / predicted (gap) | "
            "Edge mAP oracle / predicted |", "|---|---|---|---|"]
    for s in splits:
        o, p = get("final_test_oracle", s), get("final_test", s)
        out.append(f"| {NAMES[s]} | {f3(o['node_AP50'])} / {f3(p['node_AP50'])} | "
                   f"{f3(o['edges']['f1'])} / {f3(p['edges']['f1'])} "
                   f"({p['edges']['f1'] - o['edges']['f1']:+.3f}) | "
                   f"{f3(o['pid2graph_edge_map']['edge_mAP'])} / "
                   f"{f3(p['pid2graph_edge_map']['edge_mAP'])} |")

    # robustness
    levels = [("clean", "final_test"), ("L1", "final_test_L1"), ("L2", "final_test_L2"),
              ("L3", "final_test_L3")]
    out += ["", "## Robustness (degradation simulator, configs/degrade.yaml)", "",
            "Stage metrics: detection = symbol mAP@0.5, nodes = node AP@0.5, connectivity = "
            "edge F1. ![robustness](robustness.png)", "",
            "| test set | level | Symbols mAP@0.5 | Nodes AP | Edge F1 | Edge mAP |",
            "|---|---|---|---|---|---|"]
    curves: dict[str, dict[str, list[float]]] = {}
    for s in splits:
        curves[s] = {"detection": [], "nodes": [], "connectivity": []}
        for name, run in levels:
            m = get(run, s)
            curves[s]["detection"].append(m["symbols"]["mAP50"])
            curves[s]["nodes"].append(m["node_AP50"])
            curves[s]["connectivity"].append(m["edges"]["f1"])
            out.append(f"| {NAMES[s]} | {name} | {f3(m['symbols']['mAP50'])} | "
                       f"{f3(m['node_AP50'])} | {f3(m['edges']['f1'])} | "
                       f"{f3(m['pid2graph_edge_map']['edge_mAP'])} |")
    plot_robustness(curves, [n for n, _ in levels])

    # ablations
    abl = [("crop off", "abl_no_crop", "final_test"),
           ("ankle-port rule off", "abl_no_ankle_ports", "final_test"),
           ("dashed join tolerance off", "abl_no_dashed_tol", "final_test"),
           ("confidence model off (all scores 1.0)", "abl_no_confidence", "final_test"),
           ("deskew off (at degradation L2)", "abl_no_deskew_L2", "final_test_L2")]
    out += ["", "## Ablations (one decision switched off; Δ vs the final configuration)", "",
            "| ablation | test set | Edge F1 (Δ) | Edge mAP (Δ) | Nodes AP (Δ) |",
            "|---|---|---|---|---|"]
    for label, run, base in abl:
        for s in splits:
            a, b = get(run, s), get(base, s)

            def d(key: str, a: dict[str, Any] = a, b: dict[str, Any] = b) -> str:
                va = a["edges"]["f1"] if key == "f1" else (
                    a["pid2graph_edge_map"]["edge_mAP"] if key == "map" else a["node_AP50"])
                vb = b["edges"]["f1"] if key == "f1" else (
                    b["pid2graph_edge_map"]["edge_mAP"] if key == "map" else b["node_AP50"])
                return f"{f3(va)} ({va - vb:+.3f})"

            out.append(f"| {label} | {NAMES[s]} | {d('f1')} | {d('map')} | {d('nodes')} |")
    out += ["", "OPEN100 oversampling ablation: RESULTS R-003 (same 8 OPEN100 test sheets, "
            "symbol mAP 0.397 without OPEN100 training sheets vs 0.704 with)."]

    # DEXPI
    out += ["", "## Export validity (final test predictions)", "",
            "| test set | GraphML invalid | DEXPI invalid | symbols mapped to DEXPI | "
            "unmapped |", "|---|---|---|---|---|"]
    for s in splits:
        m = get("final_test", s)
        rep = m.get("dexpi_report", {})
        unm = rep.get("unmapped_symbols", {})
        mapped = sum(v for k, v in rep.get("exported", {}).items()
                     if k in ("tank", "pump", "valve", "instrumentation"))
        out.append(f"| {NAMES[s]} | {m['n_invalid_graphml']}/{m['n_drawings']} | "
                   f"{m.get('n_invalid_dexpi', '?')}/{m['n_drawings']} | {mapped} | "
                   f"{', '.join(f'{k} {v}' for k, v in sorted(unm.items()))} |")

    # paper context
    out += ["", "## Context: published numbers (not comparable)", "",
            "Stürmer et al. (2025) Table III, stitched. Different, unreleased training data and "
            "full-subset test sets; their Dataset-P&ID edges are single-class. Shown for scale "
            "only.", "",
            "| method | test set | Symbols mAP | Nodes AP | Edge mAP |", "|---|---|---|---|---|",
            "| Modular Digitization (paper) | OPEN100 (12) | 76.99 | 52.14 | 45.89 |",
            "| Relationformer (paper) | OPEN100 (12) | 73.14 | 83.63 | 75.46 |"]
    o = get("final_test", "open100_test")
    out.append(f"| this work | OPEN100 (8) | {100 * o['symbols']['mAP50']:.2f} | "
               f"{100 * o['node_AP50']:.2f} | {100 * o['pid2graph_edge_map']['edge_mAP']:.2f} |")

    resolve("docs/FINAL_RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    block = "\n".join(readme_block(cfg, get, meta))
    for path in (resolve("RESULTS.md"), resolve("README.md")):
        text = path.read_text(encoding="utf-8")
        if START in text and END in text:
            text = text[:text.index(START)] + block + text[text.index(END) + len(END):]
        else:
            raise SystemExit(f"{path}: add the markers {START} / {END} where the table goes")
        path.write_text(text, encoding="utf-8")
    print("wrote docs/FINAL_RESULTS.md, docs/robustness.png, RESULTS.md and README.md blocks")


def plot_robustness(curves: dict[str, dict[str, list[float]]], levels: list[str]) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, len(curves), figsize=(3.6 * len(curves), 3.2), dpi=120,
                             sharey=True)
    colors = {"detection": "#2a6fdb", "nodes": "#e08a1e", "connectivity": "#2e9e5b"}
    for ax, (split, c) in zip(axes, curves.items(), strict=True):
        for stage, vals in c.items():
            ax.plot(levels, vals, marker="o", lw=1.6, color=colors[stage], label=stage)
        ax.set_title(NAMES[split], fontsize=9)
        ax.set_ylim(0, 1.02)
        ax.grid(alpha=0.25)
        ax.set_xlabel("degradation level")
    axes[0].set_ylabel("metric")
    axes[0].legend(fontsize=7, frameon=False, loc="lower left")
    fig.suptitle("Test metrics under scan degradation (detection = symbol mAP@0.5, "
                 "nodes = node AP, connectivity = edge F1)", fontsize=8)
    fig.tight_layout()
    fig.savefig(resolve("docs/robustness.png"))


if __name__ == "__main__":
    main()
